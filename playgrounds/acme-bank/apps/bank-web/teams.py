"""Teams: the users of the AI workspace ACME Bank Teams, each with a budget and an API key.

The keys are generated by Gravitee. They are read from the Gamma API when first needed and again after a 401 (a
re-seed makes new ones), and they never leave this server.
"""
import asyncio
import logging

import httpx

import llm
from links import Links
from management import Management
from people import TEAMS
from settings import Settings
from upstream import UpstreamError

log = logging.getLogger("bank-web.teams")

WORKSPACE = "ACME Bank Teams"
SOURCE = "gravitee"
MODEL_LABELS = {"qwen3:1.7b": "smart", "qwen3:0.6b": "lite"}
PROMPTS = {
    "short": ("In one sentence, what does a bank do with the money you deposit?", 60),
    "long": ("Explain in detail how a mortgage works, step by step, with an example.", 400),
}
MICRODOLLARS = 1_000_000          # the gateway reports a cost budget in millionths of a dollar


class TeamKeys:
    def __init__(self, management: Management):
        self.management = management
        self.workspace: dict = {}
        self._keys: dict[str, str] = {}
        self._lock = asyncio.Lock()

    async def key(self, team: str) -> str:
        if team not in self._keys:
            await self.refresh()
        return self._keys[team]

    async def warm(self) -> None:
        """Read the keys once at start. The workspace may not exist yet (the seed runs after the apps): the first
        use then reads them."""
        try:
            await self.refresh()
        except UpstreamError as e:
            log.info("the keys of the teams are not read yet: %s", e.message)

    async def refresh(self) -> None:
        async with self._lock:
            workspace = await self._find_workspace()
            members = await self._members(workspace["id"])
            keys = {}
            for team, _ in TEAMS:
                subscription = members.get(await self._user_id(team))
                if subscription is None:
                    raise UpstreamError(f"{team} is not a user of the AI workspace. Re-seed the playground.", 503)
                answer = await self.management.get(
                    f"{self.management.modules}/aim/ai-workspaces/{workspace['id']}/users/{subscription}/api-key")
                if not isinstance(answer, dict) or not answer.get("apiKey"):
                    raise UpstreamError(f"The Gamma API gave no API key for {team}", 502)
                keys[team] = answer["apiKey"]
            self.workspace, self._keys = workspace, keys
            log.info("read the keys of %d teams from the Gamma API", len(keys))

    async def current_workspace(self) -> dict:
        """The workspace as the platform has it now (a re-seed makes it again, with its own deployment state)."""
        return await self._find_workspace()

    async def _find_workspace(self) -> dict:
        base = f"{self.management.modules}/aim/ai-workspaces"
        found = await self.management.get(base, q=WORKSPACE, page=1, perPage=50)
        match = next((w for w in found.get("data", []) if w.get("name") == WORKSPACE), None)
        if match is None:
            raise UpstreamError(f"The AI workspace {WORKSPACE} does not exist. Re-seed the playground.", 503)
        return await self.management.get(f"{base}/{match['id']}")

    async def _members(self, workspace_id: str) -> dict[str, str]:
        """subscription id of each user of the workspace, by platform user id"""
        rows = await self.management.get(f"{self.management.modules}/aim/ai-workspaces/{workspace_id}/users",
                                         page=1, perPage=100)
        return {row["userId"]: row["subscriptionId"] for row in rows.get("data", [])}

    async def _user_id(self, source_id: str) -> str | None:
        found = await self.management.get(f"{self.management.v1}/users", q=source_id, size=100)
        user = next((u for u in found.get("data", []) if u.get("source") == SOURCE and u.get("sourceId") == source_id), None)
        return user["id"] if user else None


class Teams:
    def __init__(self, http: httpx.AsyncClient, settings: Settings, keys: TeamKeys, links: Links):
        self.http, self.settings, self.keys, self.links = http, settings, keys, links

    async def spend_link(self) -> str | None:
        """Where the workspace's Spend page is, once the workspace is known."""
        if not self.keys.workspace:
            try:
                await self.keys.refresh()
            except UpstreamError:
                return None
        return self.links.spend(self.keys.workspace.get("id"))

    async def chat(self, team: str, kind: str) -> dict:
        prompt, max_tokens = PROMPTS[kind]
        payload = {"model": "smart", "messages": [{"role": "user", "content": prompt}], "max_tokens": max_tokens,
                   "reasoning_effort": "none"}       # a small max_tokens would otherwise be spent thinking
        result = await self._post(team, payload)
        if result["status"] == 401:                   # the key was replaced since it was read
            await self.keys.refresh()
            result = await self._post(team, payload)
        return {**result, "team": team, "model": self._label(result["model"]), "budget": self._budget(result["limits"])}

    async def _post(self, team: str, payload: dict) -> dict:
        key = await self.keys.key(team)
        path = self.keys.workspace.get("contextPath")
        if not path:
            raise UpstreamError(f"The AI workspace {WORKSPACE} has no model yet. Re-seed the playground.", 503)
        return await llm.complete(self.http, f"{self.settings.gateway_url.rstrip('/')}{path}",
                                  {"Authorization": f"Bearer {key}"}, payload, "x-cost-rate-limit")

    @staticmethod
    def _label(model: str | None) -> str | None:
        return MODEL_LABELS.get(model, model)

    @staticmethod
    def _budget(limits: dict | None) -> dict | None:
        """The member's budget in dollars: what it is, what is left, and the share left."""
        if not limits or limits["limit"] is None or limits["remaining"] is None or limits["limit"] <= 0:
            return None
        return {"limit": limits["limit"] / MICRODOLLARS, "left": limits["remaining"] / MICRODOLLARS,
                "percent_left": max(0, min(100, round(100 * limits["remaining"] / limits["limit"])))}
